CREATE OR REPLACE FUNCTION public.criar_transacao_parcelada()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$DECLARE
    v_numero INTEGER;

    v_valor_base NUMERIC(12,2);
    v_valor_parcela NUMERIC(12,2);
    v_total_anteriores NUMERIC(12,2);

    v_primeiro_vencimento DATE;
    v_data_vencimento DATE;
BEGIN
    IF NEW.modalidade <> 'Parcelado' THEN
        RETURN NEW;
    END IF;

    v_valor_base :=
        TRUNC(
            NEW.valor / NEW.qtd_parcelas,
            2
        );

    v_total_anteriores :=
        v_valor_base
        * (NEW.qtd_parcelas - 1);

    v_primeiro_vencimento :=
        calcular_vencimento(
            NEW.id_conta,
            NEW.data_inicio
        );

    FOR v_numero IN 1..NEW.qtd_parcelas
    LOOP

        IF v_numero = NEW.qtd_parcelas THEN
            v_valor_parcela :=
                NEW.valor
                - v_total_anteriores;
        ELSE
            v_valor_parcela :=
                v_valor_base;
        END IF;

        v_data_vencimento :=
            (
                v_primeiro_vencimento
                + (
                    (v_numero - 1)
                    * INTERVAL '1 month'
                )
            )::DATE;

        INSERT INTO transacoes (
            id_recorrencia,
            id_meta,
            id_conta_origem,
            id_categoria,
            nome,
            descricao,
            tipo_transacao,
            forma_pagamento,
            destino,
            valor_transacao,
            numero_parcela,
            status_transacao,
            data_transacao,
            data_vencimento,
            data_pagamento
        )
        VALUES (
            NEW.id_recorrencia,
            NEW.id_meta,
            NEW.id_conta,
            NEW.id_categoria,
            NEW.nome,
            NEW.descricao,
            NEW.tipo_transacao,
            NEW.forma_pagamento,
            NEW.destino,
            v_valor_parcela,
            v_numero,
            'Pendente',
            NEW.data_inicio,
            v_data_vencimento,
            NULL
        );

    END LOOP;

    RETURN NEW;
END;$function$

CREATE OR REPLACE FUNCTION public.criar_transacao_periodica()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$DECLARE
    v_numero INTEGER := 1;

    v_data_ocorrencia DATE;
    v_data_vencimento DATE;

    v_limite_data DATE;
BEGIN
    IF NEW.modalidade <> 'Periodico' THEN
        RETURN NEW;
    END IF;

    v_limite_data :=
        (
            CURRENT_DATE
            + INTERVAL '12 months'
        )::DATE;

    LOOP

        IF NEW.qtd_parcelas IS NOT NULL
           AND v_numero > NEW.qtd_parcelas THEN
            EXIT;
        END IF;

        IF NEW.frequencia = 'Semanal' THEN

            v_data_ocorrencia :=
                NEW.data_inicio
                + ((v_numero - 1) * 7);

        ELSIF NEW.frequencia = 'Mensal' THEN

            v_data_ocorrencia :=
                (
                    NEW.data_inicio
                    + (
                        (v_numero - 1)
                        * INTERVAL '1 month'
                    )
                )::DATE;

        ELSIF NEW.frequencia = 'Anual' THEN

            v_data_ocorrencia :=
                (
                    NEW.data_inicio
                    + (
                        (v_numero - 1)
                        * INTERVAL '1 year'
                    )
                )::DATE;

        ELSE
            RAISE EXCEPTION
                'Frequência inválida: %',
                NEW.frequencia;
        END IF;

        IF v_data_ocorrencia > v_limite_data THEN
            EXIT;
        END IF;

        v_data_vencimento :=
            calcular_vencimento(
                NEW.id_conta,
                v_data_ocorrencia
            );

        INSERT INTO transacoes (
            id_recorrencia,
            id_meta,
            id_conta_origem,
            id_categoria,
            nome,
            descricao,
            tipo_transacao,
            forma_pagamento,
            destino,
            valor_transacao,
            numero_parcela,
            status_transacao,
            data_transacao,
            data_vencimento,
            data_pagamento
        )
        VALUES (
            NEW.id_recorrencia,
            NEW.id_meta,
            NEW.id_conta,
            NEW.id_categoria,
            NEW.nome,
            NEW.descricao,
            NEW.tipo_transacao,
            NEW.forma_pagamento,
            NEW.destino,
            NEW.valor,
            v_numero,
            'Pendente',
            v_data_ocorrencia,
            v_data_vencimento,
            NULL
        );

        v_numero :=
            v_numero + 1;

    END LOOP;

    RETURN NEW;
END;$function$

CREATE OR REPLACE FUNCTION public.atualizar_transacoes_recorrencia()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$DECLARE
    v_total_pago NUMERIC(15,2);
    v_qtd_pagas INTEGER;
    v_qtd_pendentes INTEGER;
    v_valor_restante NUMERIC(15,2);
    v_valor_base NUMERIC(15,2);
    v_valor_parcela NUMERIC(15,2);
    v_data DATE;
    v_limite DATE;

    v_recriar BOOLEAN;
    v_troca_entrada BOOLEAN;

    v_indice INTEGER;
    i INTEGER;
BEGIN

    -- =====================================================
    -- 1. IDENTIFICA AS ALTERAÇÕES
    -- =====================================================

    v_troca_entrada :=
        NEW.tipo_transacao = 'Entrada'
        AND OLD.tipo_transacao IS DISTINCT FROM NEW.tipo_transacao;

    v_recriar :=
        v_troca_entrada
        OR OLD.qtd_parcelas IS DISTINCT FROM NEW.qtd_parcelas
        OR OLD.modalidade IS DISTINCT FROM NEW.modalidade
        OR OLD.ativo IS DISTINCT FROM NEW.ativo
        OR (
            NEW.modalidade = 'Periodico'
            AND OLD.frequencia IS DISTINCT FROM NEW.frequencia
        );

    -- =====================================================
    -- 2. ATUALIZA OS CAMPOS DAS TRANSAÇÕES PENDENTES
    -- =====================================================

    UPDATE public.transacoes
    SET
        id_meta = NEW.id_meta,
        id_conta_origem = NEW.id_conta,
        id_categoria = NEW.id_categoria,
        tipo_transacao = NEW.tipo_transacao,
        nome = NEW.nome,
        descricao = NEW.descricao,
        forma_pagamento = NEW.forma_pagamento,
        destino = NEW.destino
    WHERE id_recorrencia = NEW.id_recorrencia
      AND status_transacao = 'Pendente'
      AND (
          id_meta,
          id_conta_origem,
          id_categoria,
          tipo_transacao,
          nome,
          descricao,
          forma_pagamento,
          destino
      ) IS DISTINCT FROM (
          NEW.id_meta,
          NEW.id_conta,
          NEW.id_categoria,
          NEW.tipo_transacao,
          NEW.nome,
          NEW.descricao,
          NEW.forma_pagamento,
          NEW.destino
      );

    -- =====================================================
    -- 3. ALTERAÇÃO PARA ENTRADA
    -- Exclui todas as transações, inclusive pagas
    -- =====================================================

    IF v_troca_entrada THEN

        DELETE FROM public.transacoes
        WHERE id_recorrencia = NEW.id_recorrencia;

    END IF;

    -- =====================================================
    -- 4. DESATIVAÇÃO DA RECORRÊNCIA
    -- =====================================================

    IF NEW.ativo = FALSE THEN

        DELETE FROM public.transacoes
        WHERE id_recorrencia = NEW.id_recorrencia
          AND status_transacao = 'Pendente';

        RETURN NEW;

    END IF;

    -- =====================================================
    -- 5. CONSULTA AS TRANSAÇÕES PAGAS
    -- =====================================================

    SELECT
        COALESCE(SUM(valor_transacao), 0),
        COUNT(*)
    INTO
        v_total_pago,
        v_qtd_pagas
    FROM public.transacoes
    WHERE id_recorrencia = NEW.id_recorrencia
      AND status_transacao = 'Pago';

    -- =====================================================
    -- 6. ATUALIZA DATAS DE VENCIMENTO
    -- Sem excluir transações, inclusive as pagas
    -- =====================================================

    IF OLD.data_inicio IS DISTINCT FROM NEW.data_inicio THEN

        UPDATE public.transacoes
        SET data_vencimento =
            CASE NEW.modalidade

                WHEN 'Parcelado' THEN
                    (
                        NEW.data_inicio
                        + MAKE_INTERVAL(months => numero_parcela - 1)
                    )::DATE

                WHEN 'Periodico' THEN
                    CASE NEW.frequencia

                        WHEN 'Semanal' THEN
                            NEW.data_inicio + (numero_parcela - 1) * 7

                        WHEN 'Mensal' THEN
                            (
                                NEW.data_inicio
                                + MAKE_INTERVAL(months => numero_parcela - 1)
                            )::DATE

                        WHEN 'Anual' THEN
                            (
                                NEW.data_inicio
                                + MAKE_INTERVAL(years => numero_parcela - 1)
                            )::DATE

                    END
            END
        WHERE id_recorrencia = NEW.id_recorrencia
          AND numero_parcela IS NOT NULL;

    END IF;

    -- =====================================================
    -- 7. RECORRÊNCIA PARCELADA
    -- =====================================================

    IF NEW.modalidade = 'Parcelado' THEN

        -- Valida quantidade
        IF NEW.qtd_parcelas IS NULL
           OR NEW.qtd_parcelas < 1 THEN

            RAISE EXCEPTION
                'A quantidade de parcelas deve ser maior que zero.';

        END IF;

        -- Não permite quantidade inferior às pagas
        IF NEW.qtd_parcelas < v_qtd_pagas THEN

            RAISE EXCEPTION
                'A quantidade de parcelas não pode ser menor que a quantidade paga.';

        END IF;

        -- Impede excluir posições já pagas
        IF EXISTS (
            SELECT 1
            FROM public.transacoes
            WHERE id_recorrencia = NEW.id_recorrencia
              AND status_transacao = 'Pago'
              AND (
                  numero_parcela IS NULL
                  OR numero_parcela < 1
                  OR numero_parcela > NEW.qtd_parcelas
              )
        ) THEN

            RAISE EXCEPTION
                'Existem parcelas pagas incompatíveis com a nova quantidade.';

        END IF;

        -- Calcula valor restante
        v_valor_restante :=
            ROUND(NEW.valor - v_total_pago, 2);

        IF v_valor_restante < 0 THEN

            RAISE EXCEPTION
                'O valor total não pode ser menor que o valor já pago.';

        END IF;

        -- Quantidade que falta pagar
        v_qtd_pendentes :=
            NEW.qtd_parcelas - v_qtd_pagas;

        -- Verifica consistência financeira
        IF v_qtd_pendentes = 0
           AND v_valor_restante <> 0 THEN

            RAISE EXCEPTION
                'Todas as parcelas já estão pagas. O valor total deve corresponder ao total pago.';

        END IF;

        IF v_qtd_pendentes > 0
           AND v_valor_restante < v_qtd_pendentes * 0.01 THEN

            RAISE EXCEPTION
                'O valor restante é insuficiente para gerar parcelas positivas.';

        END IF;

        -- Calcula valor das parcelas pendentes
        IF v_qtd_pendentes > 0 THEN

            v_valor_base :=
                TRUNC(v_valor_restante / v_qtd_pendentes, 2);

        END IF;

        -- =================================================
        -- 7.1. RECRIAÇÃO DAS PARCELAS
        -- Apenas quando necessário
        -- =================================================

        -- Verifica se faltam transações pendentes
        IF NOT v_recriar THEN

            IF (
                SELECT COUNT(*)
                FROM public.transacoes
                WHERE id_recorrencia = NEW.id_recorrencia
                  AND status_transacao = 'Pendente'
            ) <> v_qtd_pendentes THEN

                v_recriar := TRUE;

            END IF;

        END IF;

        IF v_recriar THEN

            -- Exclui somente as pendentes
            DELETE FROM public.transacoes
            WHERE id_recorrencia = NEW.id_recorrencia
              AND status_transacao = 'Pendente';

            v_indice := 0;

            FOR i IN 1..NEW.qtd_parcelas LOOP

                -- Preserva parcelas pagas
                IF EXISTS (
                    SELECT 1
                    FROM public.transacoes
                    WHERE id_recorrencia = NEW.id_recorrencia
                      AND numero_parcela = i
                      AND status_transacao = 'Pago'
                ) THEN

                    CONTINUE;

                END IF;

                v_indice := v_indice + 1;

                -- Ajusta centavos na última parcela
                IF v_indice = v_qtd_pendentes THEN

                    v_valor_parcela :=
                        v_valor_restante
                        - v_valor_base * (v_qtd_pendentes - 1);

                ELSE

                    v_valor_parcela := v_valor_base;

                END IF;

                -- Vencimento mensal
                v_data :=
                    (
                        NEW.data_inicio
                        + MAKE_INTERVAL(months => i - 1)
                    )::DATE;

                INSERT INTO public.transacoes (
                    id_recorrencia,
                    id_meta,
                    numero_parcela,
                    id_conta_origem,
                    id_categoria,
                    tipo_transacao,
                    nome,
                    descricao,
                    forma_pagamento,
                    destino,
                    valor_transacao,
                    status_transacao,
                    data_transacao,
                    data_vencimento,
                    data_pagamento
                )
                VALUES (
                    NEW.id_recorrencia,
                    NEW.id_meta,
                    i,
                    NEW.id_conta,
                    NEW.id_categoria,
                    NEW.tipo_transacao,
                    NEW.nome,
                    NEW.descricao,
                    NEW.forma_pagamento,
                    NEW.destino,
                    v_valor_parcela,
                    'Pendente',
                    v_data,
                    v_data,
                    NULL
                );

            END LOOP;

        -- =================================================
        -- 7.2. ALTERAÇÃO APENAS DO VALOR
        -- UPDATE, sem DELETE nem INSERT
        -- =================================================

        ELSIF OLD.valor IS DISTINCT FROM NEW.valor THEN

            WITH parcelas AS (
                SELECT
                    id_transacao,
                    ROW_NUMBER() OVER (
                        ORDER BY numero_parcela, id_transacao
                    ) AS posicao
                FROM public.transacoes
                WHERE id_recorrencia = NEW.id_recorrencia
                  AND status_transacao = 'Pendente'
            )

            UPDATE public.transacoes AS t
            SET valor_transacao =
                CASE
                    WHEN p.posicao = v_qtd_pendentes THEN
                        v_valor_restante
                        - v_valor_base * (v_qtd_pendentes - 1)

                    ELSE v_valor_base
                END
            FROM parcelas AS p
            WHERE t.id_transacao = p.id_transacao;

        END IF;

    -- =====================================================
    -- 8. RECORRÊNCIA PERIÓDICA
    -- =====================================================

    ELSIF NEW.modalidade = 'Periodico' THEN

        -- Quando apenas o valor muda, atualiza sem excluir
        IF OLD.valor IS DISTINCT FROM NEW.valor
           AND NOT v_recriar THEN

            UPDATE public.transacoes
            SET valor_transacao = NEW.valor
            WHERE id_recorrencia = NEW.id_recorrencia
              AND status_transacao = 'Pendente';

        END IF;

        -- Recria somente quando necessário
        IF v_recriar THEN

            DELETE FROM public.transacoes
            WHERE id_recorrencia = NEW.id_recorrencia
              AND status_transacao = 'Pendente';

        END IF;

        -- Gera ocorrências faltantes até 12 meses à frente
        -- Também funciona quando ativo muda para TRUE
        IF v_recriar THEN

            v_limite :=
                (CURRENT_DATE + INTERVAL '12 months')::DATE;

            FOR i IN 1..10000 LOOP

                -- Respeita a quantidade informada
                IF NEW.qtd_parcelas IS NOT NULL
                   AND i > NEW.qtd_parcelas THEN

                    EXIT;

                END IF;

                -- Calcula data pela frequência
                v_data :=
                    CASE NEW.frequencia

                        WHEN 'Semanal' THEN
                            NEW.data_inicio + (i - 1) * 7

                        WHEN 'Mensal' THEN
                            (
                                NEW.data_inicio
                                + MAKE_INTERVAL(months => i - 1)
                            )::DATE

                        WHEN 'Anual' THEN
                            (
                                NEW.data_inicio
                                + MAKE_INTERVAL(years => i - 1)
                            )::DATE

                    END;

                IF v_data IS NULL THEN

                    RAISE EXCEPTION
                        'Frequência inválida para recorrência periódica.';

                END IF;

                -- Não gera além dos próximos 12 meses
                IF v_data > v_limite THEN

                    EXIT;

                END IF;

                -- Não recria ocorrências anteriores a hoje
                IF v_data < CURRENT_DATE THEN

                    CONTINUE;

                END IF;

                -- Não duplica ocorrências pagas
                IF EXISTS (
                    SELECT 1
                    FROM public.transacoes
                    WHERE id_recorrencia = NEW.id_recorrencia
                      AND numero_parcela = i
                      AND status_transacao = 'Pago'
                ) THEN

                    CONTINUE;

                END IF;

                -- Cria ocorrência pendente
                INSERT INTO public.transacoes (
                    id_recorrencia,
                    id_meta,
                    numero_parcela,
                    id_conta_origem,
                    id_categoria,
                    tipo_transacao,
                    nome,
