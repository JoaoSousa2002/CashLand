create table public.recorrencias (
  id_recorrencia integer generated by default as identity not null,
  id_usuario integer not null,
  id_conta integer not null,
  id_meta integer null,
  id_categoria integer null,
  tipo_transacao character varying(10) not null,
  modalidade character varying(10) not null,
  nome character varying(100) not null,
  descricao text null,
  forma_pagamento character varying(30) null,
  destino character varying(255) null,
  valor numeric(12, 2) not null,
  frequencia character varying(10) not null default 'Mensal'::character varying,
  qtd_parcelas integer null,
  data_inicio date not null,
  ativo boolean not null default true,
  data_criacao timestamp with time zone not null default now(),
