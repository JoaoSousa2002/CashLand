  constraint fk_recorrencia_meta foreign KEY (id_meta) references public.metas (id_meta),
  constraint fk_recorrencia_categoria foreign KEY (id_categoria) references categorias (id_categoria),
  constraint fk_recorrencia_conta foreign KEY (id_conta) references contas_bancarias (id_conta),
