                    forma_pagamento,
                    destino,
                    valor_transacao,
                    status_transacao,
                    data_transacao,
                    data_vencimento,
                    data_pagamento
                )
                VALUES (
                    NEW.id_recorrencia,
                    NEW.id_meta,
                    i,
                    NEW.id_conta,
                    NEW.id_categoria,
                    NEW.tipo_transacao,
                    NEW.nome,
                    NEW.descricao,
                    NEW.forma_pagamento,
                    NEW.destino,
                    NEW.valor,
                    'Pendente',
                    v_data,
