                );

            END LOOP;

        END IF;

    END IF;

    RETURN NEW;

END;$function$

CREATE OR REPLACE FUNCTION public.atualizar_saldo()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_id_conta integer;
    v_valor numeric(12,2);
    v_saldo_anterior numeric(12,2);
    v_contas integer[] := ARRAY[]::integer[];
    v_valores numeric[] := ARRAY[]::numeric[];
    v_registro record;
BEGIN

    -- ==========================================
    -- DESFAZER O EFEITO ANTERIOR
    -- ==========================================
    IF TG_OP IN ('UPDATE', 'DELETE') THEN

        IF OLD.status_transacao = 'Pago' THEN

            IF OLD.tipo_transacao = 'Entrada' THEN
                v_contas := array_append(v_contas, OLD.id_conta_origem);
                v_valores := array_append(v_valores, -OLD.valor_transacao);

            ELSIF OLD.tipo_transacao = 'Saida' THEN
                v_contas := array_append(v_contas, OLD.id_conta_origem);
                v_valores := array_append(v_valores, OLD.valor_transacao);

            ELSIF OLD.tipo_transacao = 'Transferencia' THEN
                v_contas := array_append(v_contas, OLD.id_conta_origem);
                v_valores := array_append(v_valores, OLD.valor_transacao);

                v_contas := array_append(v_contas, OLD.id_conta_destino);
                v_valores := array_append(v_valores, -OLD.valor_transacao);
            END IF;

        END IF;

    END IF;


    -- ==========================================
    -- APLICAR O EFEITO NOVO
    -- ==========================================
    IF TG_OP IN ('INSERT', 'UPDATE') THEN

        IF NEW.status_transacao = 'Pago' THEN

            IF NEW.tipo_transacao = 'Entrada' THEN
                v_contas := array_append(v_contas, NEW.id_conta_origem);
                v_valores := array_append(v_valores, NEW.valor_transacao);

            ELSIF NEW.tipo_transacao = 'Saida' THEN
                v_contas := array_append(v_contas, NEW.id_conta_origem);
                v_valores := array_append(v_valores, -NEW.valor_transacao);

            ELSIF NEW.tipo_transacao = 'Transferencia' THEN
                v_contas := array_append(v_contas, NEW.id_conta_origem);
                v_valores := array_append(v_valores, -NEW.valor_transacao);

                v_contas := array_append(v_contas, NEW.id_conta_destino);
                v_valores := array_append(v_valores, NEW.valor_transacao);
            END IF;

        END IF;

    END IF;


    -- ==========================================
    -- ATUALIZAR SALDOS DAS CONTAS AFETADAS
    -- ==========================================
    FOR v_registro IN
        SELECT
            conta,
            SUM(valor) AS diferenca
        FROM unnest(v_contas, v_valores) AS movimentos(conta, valor)
        WHERE conta IS NOT NULL
        GROUP BY conta
        HAVING SUM(valor) <> 0
        ORDER BY conta
    LOOP

        v_id_conta := v_registro.conta;
        v_valor := v_registro.diferenca;

        -- Bloqueia a conta para evitar atualizações simultâneas
        PERFORM 1
        FROM public.contas_bancarias
        WHERE id_conta = v_id_conta
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Conta % não encontrada', v_id_conta;
        END IF;


        -- ==========================================
        -- CONSULTAR SALDO ANTERIOR
        -- ==========================================
        SELECT saldo
        INTO v_saldo_anterior
        FROM public.saldo_conta
        WHERE id_conta = v_id_conta
          AND data_saldo < CURRENT_DATE
        ORDER BY data_saldo DESC
        LIMIT 1;

        v_saldo_anterior := COALESCE(v_saldo_anterior, 0);


        -- ==========================================
        -- INSERIR OU ATUALIZAR SALDO DE HOJE
        -- ==========================================
        INSERT INTO public.saldo_conta AS sc (
            id_conta,
            saldo,
            data_saldo,
            data_atualizacao
        )
        VALUES (
            v_id_conta,
            v_saldo_anterior + v_valor,
            CURRENT_DATE,
            CURRENT_TIMESTAMP
        )
        ON CONFLICT (id_conta, data_saldo)
        DO UPDATE SET
            saldo = sc.saldo + v_valor,
            data_atualizacao = CURRENT_TIMESTAMP;


        -- ==========================================
        -- ATUALIZAR SALDOS FUTUROS EXISTENTES
        -- ==========================================
        UPDATE public.saldo_conta
        SET
            saldo = saldo + v_valor,
            data_atualizacao = CURRENT_TIMESTAMP
        WHERE id_conta = v_id_conta
          AND data_saldo > CURRENT_DATE;

    END LOOP;


    -- ==========================================
    -- RETORNO DO TRIGGER
    -- ==========================================
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;

END;
$function$

CREATE OR REPLACE FUNCTION public.recalcular_valor_total_recorrencia()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
    UPDATE recorrencias
    SET valor = (
        SELECT COALESCE(SUM(valor_transacao), 0)
        FROM transacoes
        WHERE id_recorrencia = NEW.id_recorrencia
    )
    WHERE id_recorrencia = NEW.id_recorrencia
      AND modalidade = 'Parcelado';

    RETURN NEW;
END;
$function$


