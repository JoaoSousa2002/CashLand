create table public.recorrencias (
  id_recorrencia integer generated by default as identity not null,
  id_usuario integer not null,
  id_conta integer not null,
  id_categoria integer null,
  tipo_transacao character varying(10) not null,
  modalidade character varying(10) not null,
  nome character varying(100) not null,
  descricao text null,
  forma_pagamento character varying(30) null,
  destino character varying(255) null,
  valor numeric(12, 2) not null,
  frequencia character varying(10) not null default 'Mensal'::character varying,
  qtd_parcelas integer null,
  data_inicio date not null,
  ativo boolean not null default true,
  data_criacao timestamp with time zone not null default now(),
  constraint recorrencias_pkey primary key (id_recorrencia),
  constraint fk_recorrencia_categoria foreign KEY (id_categoria) references categorias (id_categoria),
  constraint fk_recorrencia_conta foreign KEY (id_conta) references contas_bancarias (id_conta),
  constraint fk_recorrencia_usuario foreign KEY (id_usuario) references usuarios (id_usuario),
  constraint chk_recorrencia_tipo check (
    (
      (tipo_transacao)::text = any (
        (
          array[
            'Entrada'::character varying,
            'Saida'::character varying
          ]
        )::text[]
      )
    )
  ),
  constraint chk_recorrencia_forma_pagamento check (
    (
      (forma_pagamento is null)
      or (
        (forma_pagamento)::text = any (
          (
            array[
              'PIX'::character varying,
              'débito'::character varying,
              'crédito'::character varying,
              'boleto'::character varying,
              'dinheiro'::character varying
            ]
          )::text[]
        )
      )
    )
  ),
  constraint chk_recorrencia_valor check ((valor > (0)::numeric)),
  constraint chk_recorrencia_frequencia check (
    (
      (frequencia)::text = any (
        (
          array[
            'Semanal'::character varying,
            'Mensal'::character varying,
            'Anual'::character varying
          ]
        )::text[]
      )
    )
  ),
  constraint chk_recorrencia_modalidade check (
    (
      (modalidade)::text = any (
        (
          array[
            'Parcelado'::character varying,
            'Periodico'::character varying
          ]
        )::text[]
      )
    )
  ),
  constraint chk_recorrencia_quantidade check (
    (
      (
        ((modalidade)::text = 'Parcelado'::text)
        and (qtd_parcelas is not null)
        and (qtd_parcelas >= 2)
      )
      or (
        ((modalidade)::text = 'Periodico'::text)
        and (
          (qtd_parcelas is null)
          or (qtd_parcelas >= 1)
        )
      )
    )
  )
) TABLESPACE pg_default;

create trigger trg_criar_transacao_parcelada
after INSERT on recorrencias for EACH row when (new.modalidade::text = 'Parcelado'::text)
execute FUNCTION criar_transacao_parcelada ();

create trigger trg_criar_transacao_periodica
after INSERT on recorrencias for EACH row when (new.modalidade::text = 'Periodico'::text)
execute FUNCTION criar_transacao_periodica ();

create trigger trigger_atualizar_transacoes_recorrencia
after
update on recorrencias for EACH row
execute FUNCTION atualizar_transacoes_recorrencia ();

create table public.transacoes (
  id_transacao integer generated by default as identity not null,
  id_recorrencia integer null,
  id_conta_origem integer not null,
  id_conta_destino integer null,
  id_categoria integer null,
  id_meta integer null,
  nome character varying(100) not null,
  descricao text null,
  tipo_transacao character varying(15) not null,
  forma_pagamento character varying(30) null,
  destino character varying(255) null,
  valor_transacao numeric(12, 2) not null,
  numero_parcela integer null,
  status_transacao character varying(10) not null default 'Pendente'::character varying,
  data_transacao date not null,
  data_vencimento date null,
  data_pagamento date null,
  data_criacao timestamp with time zone not null default now(),
  constraint transacoes_pkey primary key (id_transacao),
  constraint uq_recorrencia_parcela unique (id_recorrencia, numero_parcela),
  constraint fk_transacao_categoria foreign KEY (id_categoria) references categorias (id_categoria),
  constraint fk_transacao_conta_destino foreign KEY (id_conta_destino) references contas_bancarias (id_conta),
  constraint fk_transacao_conta_origem foreign KEY (id_conta_origem) references contas_bancarias (id_conta),
  constraint fk_transacao_recorrencia foreign KEY (id_recorrencia) references recorrencias (id_recorrencia),
  constraint chk_contas_diferentes check (
    (
      (id_conta_destino is null)
      or (id_conta_destino <> id_conta_origem)
    )
  ),
  constraint chk_transacao_valor check ((valor_transacao > (0)::numeric)),
  constraint chk_transacao_contas check (
    (
      (
        ((tipo_transacao)::text = 'Transferencia'::text)
        and (id_conta_destino is not null)
        and (id_categoria is null)
      )
      or (
        (
          (tipo_transacao)::text = any (
            (
              array[
                'Entrada'::character varying,
                'Saida'::character varying
              ]
            )::text[]
          )
        )
        and (id_conta_destino is null)
        and (id_categoria is not null)
      )
    )
  ),
  constraint chk_transacao_forma_pagamento check (
    (
      (forma_pagamento is null)
      or (
        (forma_pagamento)::text = any (
          (
            array[
              'PIX'::character varying,
              'débito'::character varying,
              'crédito'::character varying,
              'boleto'::character varying,
              'dinheiro'::character varying
            ]
          )::text[]
        )
      )
    )
  ),
  constraint chk_transacao_pagamento check (
    (
      (
        ((status_transacao)::text = 'Pago'::text)
        and (data_pagamento is not null)
      )
      or (
        ((status_transacao)::text = 'Pendente'::text)
        and (data_pagamento is null)
      )
    )
  ),
  constraint chk_transacao_status check (
    (
      (status_transacao)::text = any (
        (
          array[
            'Pendente'::character varying,
            'Pago'::character varying
          ]
        )::text[]
      )
    )
  ),
  constraint chk_transacao_tipo check (
    (
      (tipo_transacao)::text = any (
        (
          array[
            'Entrada'::character varying,
            'Saida'::character varying,
            'Transferencia'::character varying
          ]
        )::text[]
      )
    )
  )
) TABLESPACE pg_default;

create trigger trg_atualizar_saldo
after INSERT
or DELETE
or
update on transacoes for EACH row
execute FUNCTION atualizar_saldo ();

create trigger trigger_recalcular_valor_total_recorrencia
after
update OF valor_transacao on transacoes for EACH row when (
  new.id_recorrencia is not null
  and old.valor_transacao is distinct from new.valor_transacao
)
execute FUNCTION recalcular_valor_total_recorrencia ();

create table public.saldo_conta (
  id_saldo integer generated by default as identity not null,
  id_conta integer not null,
  saldo numeric(12, 2) not null default 0,
  data_saldo date not null,
  data_atualizacao timestamp with time zone not null default now(),
  constraint saldo_conta_pkey primary key (id_saldo),
  constraint uq_saldo_conta_dia unique (id_conta, data_saldo),
  constraint fk_saldo_conta foreign KEY (id_conta) references contas_bancarias (id_conta) on delete CASCADE
) TABLESPACE pg_default;
